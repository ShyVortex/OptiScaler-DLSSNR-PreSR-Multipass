void DrawFrame(bool expectedFrame, bool expectedGeometry)
{
    RenderMenuContext ctx;
    MenuCommon::BeginMenuFrameIfNeeded(ctx);
    Expect(ctx.newFrame == expectedFrame, "Wrong frame decision after closing the menu");
    if (!ctx.newFrame)
        return;
    // Foreground overlays must select their viewport even with no current window.
    auto* previousWindow = GImGui->CurrentWindow;
    GImGui->CurrentWindow = nullptr;
    DlssNr::RenderNrCompareTags();
    GImGui->CurrentWindow = previousWindow;
    ImGui::Render();
    Expect((ImGui::GetDrawData()->TotalVtxCount > 0) == expectedGeometry, "Missing overlay geometry");
}
